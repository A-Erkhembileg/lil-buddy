#!/usr/bin/env python3
"""Build Lil Buddy on the operating system where it will run.

    python -m pip install -r requirements-build.txt
    python tools/build_app.py           # macOS .app + ZIP or Windows .exe + ZIP
    python tools/build_app.py --dmg     # macOS: also make a drag-to-install DMG

PyInstaller is not a cross-compiler. Run the Windows build on Windows, or use
the repository's Build apps workflow. This script never uploads or publishes.
"""
from __future__ import annotations

import argparse
import importlib.util
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import zipfile


ROOT = Path(__file__).resolve().parents[1]
APP_NAME = "Lil Buddy"
APP_VERSION = "1.0.0"
BUNDLE_ID = "com.lilbuddy.desktop"
EXCLUDED_MODULES = ["PySide2", "PySide6", "PyQt5", "tkinter", "matplotlib",
                    "numpy", "scipy", "pandas", "IPython", "pytest"]


def generate_icons(directory: Path) -> dict[str, Path]:
    """Generate original pixel cat icons; no downloaded image/font files."""
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    from PyQt6.QtCore import QPoint, Qt
    from PyQt6.QtGui import QColor, QImage, QPainter, QPolygon
    from PyQt6.QtWidgets import QApplication
    from PIL import Image

    application = QApplication.instance() or QApplication([])
    directory.mkdir(parents=True, exist_ok=True)
    canvas = QImage(48, 48, QImage.Format.Format_ARGB32)
    canvas.fill(Qt.GlobalColor.transparent)
    painter = QPainter(canvas)
    painter.setPen(Qt.PenStyle.NoPen)
    painter.fillRect(5, 2, 38, 44, QColor("#20352b"))
    painter.fillRect(2, 5, 44, 38, QColor("#20352b"))

    def polygon(points, color):
        painter.setBrush(QColor(color))
        painter.drawPolygon(QPolygon([QPoint(x, y) for x, y in points]))

    polygon([(9, 20), (10, 9), (13, 8), (21, 15), (28, 15),
             (36, 8), (39, 10), (40, 23), (38, 35), (33, 39),
             (16, 39), (10, 34)], "#11191e")
    polygon([(11, 21), (12, 11), (13, 11), (21, 18), (28, 18),
             (36, 11), (37, 12), (38, 23), (36, 34), (32, 37),
             (17, 37), (12, 33)], "#3f4955")
    polygon([(14, 13), (19, 19), (14, 19)], "#b58296")
    polygon([(35, 13), (35, 19), (30, 19)], "#b58296")
    for x in (16, 29):
        painter.fillRect(x, 24, 6, 5, QColor("#9dff38"))
        painter.fillRect(x + 3, 24, 1, 5, QColor("#11191e"))
        painter.fillRect(x, 24, 2, 1, QColor("#d8ffae"))
    painter.fillRect(23, 31, 3, 2, QColor("#b58296"))
    painter.fillRect(22, 35, 6, 1, QColor("#78828c"))
    painter.end()
    paths = {extension: directory / f"lil-buddy.{extension}"
             for extension in ("png", "ico", "icns")}
    # Export at a standard icon size; all enlargement stays nearest-neighbor.
    image = canvas.scaled(1024, 1024, Qt.AspectRatioMode.IgnoreAspectRatio,
                          Qt.TransformationMode.FastTransformation)
    if not image.save(str(paths["png"])):
        raise RuntimeError("Could not write the generated application icon.")
    with Image.open(paths["png"]) as source:
        source.save(paths["ico"], format="ICO", sizes=[(16,16), (24,24), (32,32),
                    (48,48), (64,64), (128,128), (256,256)])
        source.save(paths["icns"], format="ICNS")
    # Keep QApplication alive until Qt has finished all icon operations.
    application.processEvents()
    return paths


def render_spec(host: str, root: Path, icons: dict[str, Path], notices: Path | None = None) -> str:
    """Render an explicit spec so the macOS metadata exists before signing."""
    if host not in ("darwin", "win32"):
        raise ValueError("Build apps on macOS or Windows; cross-compilation is unsupported.")
    imports = ["AppKit", "Foundation", "CoreFoundation", "objc"] if host == "darwin" else []
    data = [(str(notices), "Licenses")] if notices is not None else []
    icon = str(icons["icns" if host == "darwin" else "ico"])
    analysis = f'''# Generated by tools/build_app.py; do not edit.
a = Analysis(
    [{str(root / "desktop_cat.py")!r}],
    pathex=[{str(root)!r}], binaries=[], datas={data!r},
    hiddenimports={imports!r}, hookspath=[], runtime_hooks=[],
    excludes={EXCLUDED_MODULES!r}, noarchive=False, optimize=1,
)
pyz = PYZ(a.pure)
'''
    common = f'''name={APP_NAME!r}, debug=False, bootloader_ignore_signals=False,
    strip=False, upx=False, console=False, disable_windowed_traceback=False,
    icon={icon!r}, argv_emulation=False, target_arch=None,
    codesign_identity=None, entitlements_file=None,
'''
    if host == "win32":
        return analysis + f'''exe = EXE(pyz, a.scripts, a.binaries, a.datas, [],
    {common})
'''
    return analysis + f'''exe = EXE(pyz, a.scripts, [], exclude_binaries=True,
    {common})
collection = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name={APP_NAME!r})
app = BUNDLE(collection, name={APP_NAME + ".app"!r}, icon={icon!r},
    bundle_identifier={BUNDLE_ID!r}, version={APP_VERSION!r},
    info_plist={{
        "CFBundleName": {APP_NAME!r},
        "CFBundleDisplayName": {APP_NAME!r},
        "CFBundleShortVersionString": {APP_VERSION!r},
        "CFBundleVersion": "1",
        "LSUIElement": True,
        "NSHighResolutionCapable": True,
        "NSSupportsAutomaticGraphicsSwitching": True,
        "NSHumanReadableCopyright": "Lil Buddy contributors",
    }},
)
'''


def prepare_distribution_notices(root: Path, destination: Path) -> None:
    """Include licenses, matching application source, and build provenance."""
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    shutil.copy2(root / "LICENSE", destination / "LICENSE.txt")
    shutil.copy2(root / "THIRD_PARTY_NOTICES.md", destination / "THIRD_PARTY_NOTICES.md")
    shutil.copytree(root / "licenses", destination / "licenses")
    source_names = ["desktop_cat.py", "requirements.txt", "requirements-build.txt",
                    "README.md", "LICENSE", "THIRD_PARTY_NOTICES.md"]
    for folder in ("tools", "packaging/icons", "licenses", "tests", "artwork", ".github/workflows"):
        source_names.extend(str(p.relative_to(root)) for p in sorted((root / folder).rglob("*"))
                            if p.is_file() and "__pycache__" not in p.parts)
    with zipfile.ZipFile(destination / "Application-Source.zip", "w", zipfile.ZIP_DEFLATED) as archive:
        for name in sorted(set(source_names)):
            archive.write(root / name, name)
    packages = {}
    for package in ("PyQt6", "PyQt6-Qt6", "PyQt6-sip", "pyobjc-core",
                    "pyobjc-framework-Cocoa", "PyInstaller", "Pillow"):
        try:
            packages[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            continue
    try:
        result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, capture_output=True, text=True)
        commit = result.stdout.strip() if result.returncode == 0 else None
    except FileNotFoundError:
        commit = None
    info = {"application": APP_NAME, "version": APP_VERSION, "commit": commit,
            "python": platform.python_version(), "system": platform.system(),
            "architecture": platform.machine(), "packages": packages,
            "source": "Application-Source.zip",
            "repository": "https://github.com/A-Erkhembileg/lil-buddy"}
    (destination / "build-info.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")


def write_windows_zip(executable: Path, destination: Path, license_path: Path,
                      notices: Path | None = None) -> None:
    """One double-clickable executable and its short installation notes."""
    instructions = (
        "Lil Buddy for Windows\n\n"
        "Extract this ZIP, then double-click Lil Buddy.exe. Python is not required.\n"
        "Use the system tray icon to show, hide, pause, or quit the pet.\n"
        "Right-click the pet to choose an animal, color, size, and habits.\n"
        "Left-click to pet it; left-drag to pick it up.\n"
        "Preferences are saved automatically for the current Windows user.\n"
        "Licenses, application source, and build details are in the Licenses folder.\n"
    )
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in ((executable.name, executable.read_bytes()),
                           ("LICENSE.txt", license_path.read_bytes()),
                           ("Start Here.txt", instructions.encode("utf-8"))):
            entry = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.external_attr = 0o100644 << 16
            archive.writestr(entry, data)
        if notices is not None:
            for path in sorted(notices.rglob("*")):
                if path.is_file():
                    archive.write(path, str(Path("Licenses") / path.relative_to(notices)))


def make_dmg(app: Path, destination: Path, work: Path) -> None:
    stage = work / "dmg-root"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    shutil.copytree(app, stage / app.name, symlinks=True)
    (stage / "Applications").symlink_to("/Applications", target_is_directory=True)
    (stage / "Start Here.txt").write_text(
        "Drag Lil Buddy.app to Applications, then open it.\n"
        "Use its menu-bar icon to pause, hide, or quit.\n"
        "Right-click the pet for colors, animals, size, and habits.\n",
        encoding="utf-8",
    )
    subprocess.run(["/usr/bin/hdiutil", "create", "-volname", APP_NAME,
                    "-srcfolder", str(stage), "-format", "UDZO", "-ov", str(destination)], check=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dmg", action="store_true", help="Also create a macOS drag-to-install DMG")
    parser.add_argument("--dry-run", action="store_true", help="Generate icons/spec and show the plan without building")
    options = parser.parse_args(argv)
    if sys.platform not in ("darwin", "win32"):
        parser.error("Build on macOS or Windows. PyInstaller cannot cross-compile desktop apps.")
    if options.dmg and sys.platform != "darwin":
        parser.error("--dmg requires macOS.")
    if not options.dry_run and importlib.util.find_spec("PyInstaller") is None:
        parser.error(f"Install build dependencies first: {sys.executable} -m pip install -r requirements-build.txt")

    work, destination = ROOT / "build" / "packaging", ROOT / "dist"
    work.mkdir(parents=True, exist_ok=True)
    destination.mkdir(parents=True, exist_ok=True)
    icons = generate_icons(ROOT / "packaging" / "icons")
    notices = work / "distribution-notices"
    prepare_distribution_notices(ROOT, notices)
    spec = work / "lil-buddy.spec"
    spec.write_text(render_spec(sys.platform, ROOT, icons, notices), encoding="utf-8")
    label = "macOS" if sys.platform == "darwin" else "Windows"
    arch = platform.machine().lower()
    stem = f"Lil-Buddy-{label}-{arch}"
    output = destination / (APP_NAME + (".app" if sys.platform == "darwin" else ".exe"))
    archive = destination / f"{stem}.zip"
    command = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
               "--distpath", str(destination), "--workpath", str(work / "pyinstaller"), str(spec)]
    if options.dry_run:
        print(json.dumps({"command": command, "application": str(output), "zip": str(archive)}, indent=2))
        return 0
    environment = os.environ.copy()
    environment.setdefault("PYTHONHASHSEED", "0")
    environment.setdefault("SOURCE_DATE_EPOCH", "1767225600")
    subprocess.run(command, cwd=ROOT, env=environment, check=True)
    if sys.platform == "darwin":
        subprocess.run(["/usr/bin/ditto", "-c", "-k", "--sequesterRsrc", "--keepParent",
                        str(output), str(archive)], check=True)
        if options.dmg:
            make_dmg(output, destination / f"{stem}.dmg", work)
    else:
        write_windows_zip(output, archive, ROOT / "LICENSE", notices)
    print(f"Application: {output}\nShareable archive: {archive}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
